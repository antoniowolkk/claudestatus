// Prepares a brand image (Wolkky mascot, Wolkk logo): makes the outside background
// transparent, trims empty edges, and writes Resources/<Name>.png plus an embedded
// Swift copy (Sources/ClaudeStatus/<Name>Image.swift, enum <Name>Image).
// Usage: swift scripts/prepare-image.swift path/to/image.png Wolkky
//        swift scripts/prepare-image.swift path/to/logo.png WolkkLogo
import AppKit

let root = URL(fileURLWithPath: CommandLine.arguments[0]).deletingLastPathComponent().deletingLastPathComponent()
let name = CommandLine.arguments.count > 2 ? CommandLine.arguments[2] : "Wolkky"
guard CommandLine.arguments.count > 1,
      let src = NSImage(contentsOfFile: CommandLine.arguments[1]),
      let cg = src.cgImage(forProposedRect: nil, context: nil, hints: nil) else {
    print("usage: swift scripts/prepare-image.swift image.png Name"); exit(1)
}
let w = cg.width, h = cg.height
var px = [UInt8](repeating: 0, count: w * h * 4)
let ctx = CGContext(data: &px, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w * 4,
                    space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
ctx.draw(cg, in: CGRect(x: 0, y: 0, width: w, height: h))

func i(_ x: Int, _ y: Int) -> Int { (y * w + x) * 4 }
func isBackground(_ k: Int) -> Bool {
    let a = px[k + 3]
    if a < 20 { return true }
    return px[k] > 235 && px[k + 1] > 235 && px[k + 2] > 235 // near-white
}
print("corner alpha:", px[3], "rgb:", px[0], px[1], px[2])

// Flood fill from every edge pixel through near-white/transparent pixels.
var seen = [Bool](repeating: false, count: w * h)
var stack: [(Int, Int)] = []
for x in 0..<w { stack.append((x, 0)); stack.append((x, h - 1)) }
for y in 0..<h { stack.append((0, y)); stack.append((w - 1, y)) }
while let (x, y) = stack.popLast() {
    guard x >= 0, y >= 0, x < w, y < h, !seen[y * w + x] else { continue }
    let k = i(x, y)
    guard isBackground(k) else { continue }
    seen[y * w + x] = true
    px[k] = 0; px[k + 1] = 0; px[k + 2] = 0; px[k + 3] = 0
    stack.append((x + 1, y)); stack.append((x - 1, y)); stack.append((x, y + 1)); stack.append((x, y - 1))
}

// Trim to content
var minX = w, minY = h, maxX = 0, maxY = 0
for y in 0..<h { for x in 0..<w where px[i(x, y) + 3] > 0 {
    minX = min(minX, x); maxX = max(maxX, x); minY = min(minY, y); maxY = max(maxY, y)
} }
let out = ctx.makeImage()!.cropping(to: CGRect(x: minX, y: minY, width: maxX - minX + 1, height: maxY - minY + 1))!
let rep = NSBitmapImageRep(cgImage: out)
let png = rep.representation(using: .png, properties: [:])!
try png.write(to: root.appendingPathComponent("Resources/\(name).png"))
try png.write(to: root.appendingPathComponent("docs/\(name.lowercased()).png"))

let b64 = png.base64EncodedString(options: [.lineLength76Characters, .endLineWithLineFeed])
let swift = """
// Generated by scripts/prepare-image.swift — do not edit.
// \(name), with a transparent background.
import AppKit

enum \(name)Image {
    static let image: NSImage = {
        let b64 = \"\"\"
\(b64)
\"\"\"
        guard let data = Data(base64Encoded: b64, options: .ignoreUnknownCharacters),
              let img = NSImage(data: data) else { return NSImage() }
        return img
    }()
}

"""
try swift.write(to: root.appendingPathComponent("Sources/ClaudeStatus/\(name)Image.swift"), atomically: true, encoding: .utf8)
print("✓ \(out.width)x\(out.height), \(png.count) bytes")
